import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import opentype from "opentype.js";
import { format } from "prettier";

const fontPath = resolve(
  "assets/fonts/barlow-condensed/BarlowCondensed-BlackItalic.otf",
);
const font = opentype.parse((await readFile(fontPath)).buffer);
const words = ["YEET", "YOLO"];

const entries = Object.fromEntries(
  words.map((word) => {
    const sourcePath = font.getPath(word, 0, 0, 100);
    const bounds = sourcePath.getBoundingBox();
    const padding = 3;
    const width = bounds.x2 - bounds.x1 + padding * 2;
    const height = bounds.y2 - bounds.y1 + padding * 2;
    // Normalize every path into a positive coordinate space. Stream Deck's
    // device SVG renderer clips nested viewBoxes with negative origins even
    // though librsvg and browsers render them correctly.
    const path = font.getPath(
      word,
      padding - bounds.x1,
      padding - bounds.y1,
      100,
    );
    return [
      word.toLowerCase(),
      {
        d: path.toPathData(2),
        width: Number(width.toFixed(2)),
        height: Number(height.toFixed(2)),
        viewBox: `0 0 ${Number(width.toFixed(2))} ${Number(height.toFixed(2))}`,
      },
    ];
  }),
);

const destination = resolve(
  process.env.STREAMDECK_WORDMARK_DESTINATION ?? "src/lib/wordmark-paths.ts",
);
const expected = await format(
  `// Generated by scripts/generate-wordmark-paths.mjs from Barlow Condensed Black Italic.
// The source font is licensed under the SIL Open Font License 1.1.
export const WORDMARK_PATHS = ${JSON.stringify(entries, null, 2)} as const;
`,
  { parser: "typescript" },
);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== expected)
    throw new Error(
      "src/lib/wordmark-paths.ts is stale; run npm run icons:wordmarks.",
    );
} else {
  await writeFile(destination, expected);
}
