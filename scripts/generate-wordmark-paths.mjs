import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import opentype from "opentype.js";
import { format } from "prettier";

const fontPath = resolve(
  "assets/fonts/barlow-condensed/BarlowCondensed-BlackItalic.otf",
);
const font = opentype.parse((await readFile(fontPath)).buffer);
const words = ["YEET", "YOLO"];

const entries = Object.fromEntries(
  words.map((word) => {
    const path = font.getPath(word, 0, 0, 100);
    const bounds = path.getBoundingBox();
    const padding = 3;
    return [
      word.toLowerCase(),
      {
        d: path.toPathData(2),
        viewBox: [
          bounds.x1 - padding,
          bounds.y1 - padding,
          bounds.x2 - bounds.x1 + padding * 2,
          bounds.y2 - bounds.y1 + padding * 2,
        ]
          .map((value) => Number(value.toFixed(2)))
          .join(" "),
      },
    ];
  }),
);

const output = `// Generated by scripts/generate-wordmark-paths.mjs from Barlow Condensed Black Italic.
// The source font is licensed under the SIL Open Font License 1.1.
export const WORDMARK_PATHS = ${JSON.stringify(entries, null, 2)} as const;
`;

await writeFile(
  resolve("src/lib/wordmark-paths.ts"),
  await format(output, { parser: "typescript" }),
);
