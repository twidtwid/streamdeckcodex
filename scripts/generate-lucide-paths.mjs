const packageRoot = resolve("node_modules/lucide-static/icons");
const entries = await Promise.all(
  Object.entries(icons).map(async ([name, file]) => {
    const svg = await readFile(resolve(packageRoot, `${file}.svg`), "utf8");
    const openingSvg = svg.indexOf("<svg");
    const inner = svg
      .slice(svg.indexOf(">", openingSvg) + 1, svg.lastIndexOf("</svg>"))
      .replaceAll(/\s+/g, " ")
      .trim();
    return [name, inner];
  }),
);

const destination = resolve(
  process.env.STREAMDECK_LUCIDE_DESTINATION ?? "src/lib/lucide-paths.ts",
);
const expected = await format(
  `// Generated by scripts/generate-lucide-paths.mjs from lucide-static.\n// Do not hand-edit; update the icon map in that script.\nexport const LUCIDE_PATHS: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`,
  { parser: "typescript" },
);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== expected)
    throw new Error(
      "src/lib/lucide-paths.ts is stale; run npm run icons:lucide.",
    );
} else {
  await writeFile(destination, expected);
}
