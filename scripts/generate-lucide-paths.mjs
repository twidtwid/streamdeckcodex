const packageRoot = resolve("node_modules/lucide-static/icons");
const entries = await Promise.all(
  Object.entries(icons).map(async ([name, file]) => {
    const svg = await readFile(resolve(packageRoot, `${file}.svg`), "utf8");
    const openingSvg = svg.indexOf("<svg");
    const inner = svg
      .slice(svg.indexOf(">", openingSvg) + 1, svg.lastIndexOf("</svg>"))
      .replaceAll(/\s+/g, " ")
      .trim();
    return [name, inner];
  }),
);

const output = `// Generated by scripts/generate-lucide-paths.mjs from lucide-static.\n// Do not hand-edit; update the icon map in that script.\nexport const LUCIDE_PATHS: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`;
await writeFile(
  resolve("src/lib/lucide-paths.ts"),
  await format(output, { parser: "typescript" }),
);
